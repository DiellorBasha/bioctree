function defs = defs()
%BCT.REGISTRY.BRUSHES.DEFS  Authoritative brush definitions registry
%
%   defs = bct.registry.brushes.defs()
%
% Purpose:
%   Single source of truth for all brush specifications in BCT.
%   This is the canonical registry - all other brush functions must
%   delegate to this.
%
% Output:
%   defs - struct array (1×K) with required fields:
%          Id            (string): unique canonical identifier
%          Category      (string): "patch"|"trajectory"|"time"|"dynamic"
%          AxisKinds     (string array): ["spatial"|"spatiotemporal"]
%          ParamNames    (string array): parameter names
%          DefaultParams (function_handle): @(manifold)->struct
%          ParamRanges   (function_handle): @(manifold)->struct
%          Evaluate      (function_handle): @(manifold,params)->w
%
%          Optional fields:
%          Name          (string): display name
%          Tags          (string array): classification tags
%          Requires      (string array): representation requirements
%          OutputDims    (string): "spatial"|"spatiotemporal"
%          Description   (string): human-readable description
%
% Contract:
%   - Evaluate(manifold, params) is the canonical signature
%   - DefaultParams(manifold) returns struct with all ParamNames
%   - ParamRanges(manifold) returns validation structs
%   - Registry must be deterministic
%
% See also: bct.registry.brushes.schema, bct.registry.brushes.validate

    % Initialize empty struct array with proper field order
    defs = initializeEmpty();
    
    %% =========================================================
    % PATCH BRUSHES (Unordered spatial selections)
    %% =========================================================
    
    defs(end+1) = definePatchNearest();
    defs(end+1) = definePatchGaussian();
    defs(end+1) = definePatchSpectral();
    
    %% =========================================================
    % TRAJECTORY BRUSHES (Ordered spatial paths)
    %% =========================================================
    
    defs(end+1) = defineTrajectoryGeodesic();
    defs(end+1) = defineTrajectoryGaussian();
    defs(end+1) = defineTrajectorySpectral();
    
    %% =========================================================
    % TIME BRUSHES (Spatiotemporal patterns)
    %% =========================================================
    
    defs(end+1) = defineTimeHeat();
    defs(end+1) = defineTimeSpectral();
    
    % NOTE: Validation is NOT called here to avoid expensive operations
    % Call bct.registry.brushes.validate(defs) explicitly if needed
end

%% =========================================================
%% INITIALIZATION HELPER
%% =========================================================

function defs = initializeEmpty()
    % Create empty struct with proper field order
    defs = struct(...
        'Id', [], ...
        'Category', [], ...
        'AxisKinds', [], ...
        'ParamNames', [], ...
        'DefaultParams', [], ...
        'ParamRanges', [], ...
        'Evaluate', [], ...
        'Name', [], ...
        'Tags', [], ...
        'Requires', [], ...
        'OutputDims', [], ...
        'Description', [] ...
    );
    defs = defs([]);  % Make 0×1 empty
end

