function spec = definePatchNearest()
    spec = struct(...
        'Id',           "patch_nearest", ...
        'Category',     "patch", ...
        'AxisKinds',    ["spatial"], ...
        'ParamNames',   ["seed", "distance", "metric"], ...
        'DefaultParams', @defaultParamsPatchNearest, ...
        'ParamRanges',  @paramRangesPatchNearest, ...
        'Evaluate',     @bct.brush.patch.nearest, ...
        'Name',         "Nearest-neighbor Patch", ...
        'Tags',         ["geometric", "binary", "distance-based"], ...
        'Requires',     ["Graph"], ...
        'OutputDims',   "spatial", ...
        'Description',  "Binary selection of vertices within distance threshold" ...
    );
end

function p = defaultParamsPatchNearest(manifold)
    charLength = computeCharacteristicLength(manifold);
    p = struct(...
        'seed',     round(manifold.numVertices() / 2), ...
        'distance', 0.05 * charLength, ...
        'metric',   "geometry" ...
    );
end

function r = paramRangesPatchNearest(manifold)
    charLength = computeCharacteristicLength(manifold);
    r = struct(...
        'seed',     struct('type', 'integer', 'range', [1, manifold.numVertices()]), ...
        'distance', struct('type', 'numeric', 'range', [0.001, 1.0] * charLength), ...
        'metric',   struct('type', 'string', 'values', ["geometry", "fem"]) ...
    );
end

