%% =========================================================
%% UTILITY FUNCTIONS
%% =========================================================

function L = computeCharacteristicLength(manifold)
    %COMPUTECHARACTERISTICLENGTH  Estimate mesh characteristic length
    %
    % Computes characteristic length from bounding box diagonal
    
    V = manifold.Vertices;
    bbox = max(V) - min(V);
    L = norm(bbox);
end
