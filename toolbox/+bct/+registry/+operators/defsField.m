function specs = defsField()
%DEFSFIELD Field-native operator specifications
%
% Returns operator specs with Field signatures for input/output.
% These are the "Phase 1" operators that accept and return Fields.
%
% Syntax:
%   specs = bct.registry.operators.defsField()
%
% Returns:
%   specs - dictionary (string → struct) with Field-native operator specs
%
% Each spec includes:
%   input/inputs  - Field signature struct(s) for inputs
%   output        - Field signature struct for output
%   acceptsRaw    - Whether raw arrays are accepted (legacy support)
%   meshPolicy    - "matchContext" (default) | "ignore" | "allowMismatch"
%   framePolicy   - "none" | "requiredForTangent2" | "requiresInputFrame" | "producesFrame"
%   metaPolicy    - "inherit" | "inheritAndAugment" | "new"
%   implementation - Function handle expecting (ctx, rawInputs...)
%
% See also: bct.registry.operators.defs, bct.fields.schema

specs = dictionary(string.empty, struct.empty);

% Helper to create Field signatures
