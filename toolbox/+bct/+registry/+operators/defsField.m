% =========================================================================
% IMPLEMENTATIONS (delegate to existing DEC methods)
% =========================================================================

function Y = impl_gradient_dec_field(ctx, X)
%IMPL_GRADIENT_DEC_FIELD Gradient implementation for Field wrapper
    dec = ctx.DEC;
    
    % Handle time-varying case
    if ndims(X) == 2 && size(X, 2) > 1
        % Time-varying: [nV×T]
        nT = size(X, 2);
        % Get number of faces from gradient output
        Y_sample = dec.gradient(X(:, 1));
        nF = size(Y_sample, 1);
        Y = zeros(nF, 3, nT);
        Y(:, :, 1) = Y_sample;
        for t = 2:nT
            Y(:, :, t) = dec.gradient(X(:, t));
        end
    else
        % Static: [nV×1]
        Y = dec.gradient(X);
    end
end

function Y = impl_divergence_dec_field(ctx, V)
%IMPL_DIVERGENCE_DEC_FIELD Divergence implementation for Field wrapper
    dec = ctx.DEC;
    
    % Handle time-varying case
    if ndims(V) == 3
        % Time-varying: [nF×3×T]
        nT = size(V, 3);
        % Get number of vertices from divergence output
        Y_sample = dec.divergence(V(:, :, 1));
        nV = length(Y_sample);
        Y = zeros(nV, nT);
        Y(:, 1) = Y_sample;
        for t = 2:nT
            Y(:, t) = dec.divergence(V(:, :, t));
        end
    else
        % Static: [nF×3]
        Y = dec.divergence(V);
    end
end

function Y = impl_laplacian_dec_field(ctx, X)
%IMPL_LAPLACIAN_DEC_FIELD Laplacian implementation for Field wrapper
    dec = ctx.DEC;
    
    % Use DEC's laplacian method (grad-div composition)
    % Handle time-varying case
    if size(X, 2) > 1
        % Time-varying: [nV×T]
        nT = size(X, 2);
        Y_sample = dec.divergence(dec.gradient(X(:, 1)));
        nV = length(Y_sample);
        Y = zeros(nV, nT);
        Y(:, 1) = Y_sample;
        for t = 2:nT
            % Laplacian via div(grad(X))
            gradX = dec.gradient(X(:, t));
            Y(:, t) = dec.divergence(gradX);
        end
    else
        % Static: [nV×1]
        gradX = dec.gradient(X);
        Y = dec.divergence(gradX);
    end
end

function Y = impl_curl_dec_field(ctx, V)
%IMPL_CURL_DEC_FIELD Curl implementation for Field wrapper
    dec = ctx.DEC;
    
    % Handle time-varying case
    if ndims(V) == 3
        curlVec_sample = dec.curl(V(:, :, 1));
        nF = size(curlVec_sample, 1);
        Y = zeros(nF, nT);
        % Return magnitude (scalar per face)
        Y(:, 1) = sqrt(sum(curlVec_sample.^2, 2));
        for t = 2:nT
            curlVec = dec.curl(V(:, :, t));
            curlVec = dec.curl(V(:, :, t));
            % Return magnitude (scalar per face)
            Y(:, t) = sqrt(sum(curlVec.^2, 2));
        end
    else
        % Static: [nF×3]
        curlVec = dec.curl(V);
        Y = sqrt(sum(curlVec.^2, 2));
    end
end
