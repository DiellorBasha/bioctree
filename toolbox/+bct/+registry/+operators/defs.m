function specs = defs()
%DEFS Return flat dictionary of operator specifications from bct.manifold.operator
%
% Syntax:
%   specs = bct.registry.operators.defs()
%
% Returns:
%   specs - dictionary (string → struct) of operator specifications
%
% All operators come from the bct.manifold.operator package:
%   - mass, stiffness, laplacebeltrami       - Mass, stiffness, Laplace-Beltrami operators
%   - d0, d1, dd0, dd1                       - Exterior derivatives (primal and dual)
%   - hd0, hd1, hd2, hdd0, hdd1, hdd2        - Hodge stars and inverses
%   - gradient                                - Gradient (vertex → face tangent vectors)
%   - divergence.primal, divergence.dual     - Divergence (two routes)
%   - curl.primal, curl.dual                 - Curl (two routes)
%   - hodgelaplacian.0, .1, .2               - Hodge Laplacian (0/1/2-forms)
%
% Each spec struct contains:
%   id             - Operator identifier (string)
%   name           - Human-friendly label
%   backend        - Backend package ("bct.manifold.operator")
%   inputSupport   - "vertex" | "edge" | "face"
%   outputSupport  - "vertex" | "edge" | "face"
%   inputType      - Input semantic type
%   outputType     - Output semantic type
%   parameters     - Parameter schema struct
%   isMatrix       - true if operator returns a matrix
%   isLinear       - true if operator is linear
%   purity         - "pure" (all manifold operators are pure)
%   description    - Brief description
%   function       - Unbound function handle to bct.manifold.operator.*
%
% See also: bct.manifold.operator, bct.runtime.operators.dictionary

% Initialize dictionary
specs = dictionary(string.empty, struct.empty);

% Build specs from bct.manifold.operator functions
specs = addMatrixOperators(specs);
specs = addPrimitiveOperators(specs);
specs = addCompositionOperators(specs);

end

%% ========================================================================
%  Helper Functions
% =========================================================================

