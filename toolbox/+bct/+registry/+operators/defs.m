function specs = addPrimitiveOperators(specs)
%ADDPRIMITIVEOPERATORS Add primitive DEC operators (d0, d1, hd0, etc.)

% All primitive operators returned by bct.manifold.operator.dec
% Exposed individually with flat naming (no "dec." prefix)

primitiveOps = {
    % Exterior derivatives
    'd0',    'Exterior Derivative (d0)', 'vertex', 'edge', 'Exterior derivative (0-form → 1-form)'
    'd1',    'Exterior Derivative (d1)', 'edge', 'face', 'Exterior derivative (1-form → 2-form)'
    'dd0',   'Dual Exterior Derivative (dd0)', 'face', 'edge', 'Dual exterior derivative (2-form → 1-form)'
    'dd1',   'Dual Exterior Derivative (dd1)', 'edge', 'vertex', 'Dual exterior derivative (1-form → 0-form)'
    
    % Hodge stars
    'hd0', 'Hodge Star (0-form)', 'vertex', 'vertex', 'Hodge star: primal 0-form → dual 2-form'
    'hd1', 'Hodge Star (1-form)', 'edge', 'edge', 'Hodge star: primal 1-form → dual 1-form'
    'hd2', 'Hodge Star (2-form)', 'face', 'face', 'Hodge star: primal 2-form → dual 0-form'
    'hdd0', 'Inverse Hodge Star (0-form)', 'vertex', 'vertex', 'Inverse Hodge: dual 2-form → primal 0-form'
    'hdd1', 'Inverse Hodge Star (1-form)', 'edge', 'edge', 'Inverse Hodge: dual 1-form → primal 1-form'
    'hdd2', 'Inverse Hodge Star (2-form)', 'face', 'face', 'Inverse Hodge: dual 0-form → primal 2-form'
    };

% Create primitive operator specs with flat IDs
for i = 1:size(primitiveOps, 1)
    opId = primitiveOps{i, 1};
    specs(opId) = struct(...
        'id', opId, ...
        'name', primitiveOps{i, 2}, ...
        'backend', "bct.manifold.operator.dec", ...
        'inputSupport', primitiveOps{i, 3}, ...
        'outputSupport', primitiveOps{i, 4}, ...
        'inputType', "k-form", ...
        'outputType', "k-form", ...
        'parameters', struct(), ...
        'isMatrix', true, ...
        'isLinear', true, ...
        'purity', "pure", ...
        'description', primitiveOps{i, 5}, ...
        'function', @(M) bct.manifold.operator.dec(M));
end

end

