%
% Syntax:
%   spec = bct.schema.geometry()
%
% Description:
%   Defines the authoritative schema for geometry structures in BCT.
%   A geometry structure contains:
%     - .attributes: Group-level metadata (extends bct.schema.group)
%     - .face:  Face geometry subgroup (7 datasets)
%     - .vertex: Vertex geometry subgroup (3 datasets)
%     - .edge:  Edge geometry subgroup (3 datasets)
