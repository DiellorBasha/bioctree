function isValid = validateGeometry(geom, varargin)
    %VALIDATEGEOMETRY Validate complete geometry structure
    %
    % Inputs:
    %   geom - Geometry structure to validate
    %
    % Name-Value Arguments:
    %   Strict - true (default) to throw errors, false to return report
    %
    % Outputs:
    %   isValid - true if valid, false otherwise
    
    p = inputParser;
    p.addRequired('geom');
    p.addParameter('Strict', true, @islogical);
    p.parse(geom, varargin{:});
    
    strict = p.Results.Strict;
    
    try
        % Get schema
        spec = bct.schema.geometry();
        
        %% Check required fields
        if ~isstruct(geom)
            error('bct:schema:geometry:NotStruct', 'Geometry must be a struct');
        end
        
        requiredFields = spec.structure.required;
        for i = 1:numel(requiredFields)
            field = requiredFields(i);
            if ~isfield(geom, field)
                error('bct:schema:geometry:MissingField', ...
                    'Required field missing: %s', field);
            end
        end
        
        %% Validate group attributes
        attrs = geom.attributes;
        
        % Validate base group fields
        bct.schema.group.validate(attrs);
        
        % Validate geometry-specific optional fields (if present)
        optionalAttrs = fieldnames(spec.attributes.optional);
        for i = 1:numel(optionalAttrs)
            fieldName = optionalAttrs{i};
            if isfield(attrs, fieldName)
                fieldSpec = spec.attributes.optional.(fieldName);
                value = attrs.(fieldName);
                
                % Type check
                if isfield(fieldSpec, 'type')
                    switch fieldSpec.type
                        case 'string'
                            if ~isstring(value) && ~ischar(value)
                                error('bct:schema:geometry:InvalidType', ...
                                    'Attribute %s must be string', fieldName);
                            end
                    end
                end
                
                % Allowed values check
                if isfield(fieldSpec, 'allowedValues')
                    if isstring(value) || ischar(value)
                        value = string(value);
                    end
                    if ~ismember(value, fieldSpec.allowedValues)
                        error('bct:schema:geometry:InvalidValue', ...
                            'Attribute %s has invalid value "%s"', fieldName, string(value));
                    end
                end
            end
        end
        
        %% Validate subgroups
        subgroupNames = ["face", "vertex", "edge", "dual"];
        
        for i = 1:numel(subgroupNames)
            subgroupName = subgroupNames(i);
            subgroup = geom.(subgroupName);
            subgroupSpec = spec.subgroups.(subgroupName);
            
            % Check that subgroup is a struct
            if ~isstruct(subgroup)
                error('bct:schema:geometry:InvalidSubgroup', ...
                    'Subgroup %s must be a struct', subgroupName);
            end
            
            % Validate each dataset in subgroup
            datasetNames = fieldnames(subgroupSpec.datasets);
            for j = 1:numel(datasetNames)
                datasetName = datasetNames{j};
                
                % Check dataset exists
                if ~isfield(subgroup, datasetName)
                    error('bct:schema:geometry:MissingDataset', ...
                        'Dataset %s.%s is missing', subgroupName, datasetName);
                end
                
                % Validate dataset structure
                dataset = subgroup.(datasetName);
                bct.schema.dataset.validate(dataset);
            end
        end
        
        %% Validation passed
        isValid = true;
        
    catch ME
        if strict
            rethrow(ME);
        end
        warning('bct:schema:geometry:ValidationFailed', ...
            'Geometry validation failed: %s', ME.message);
        isValid = false;
    end
end

function geom = makeGeometry(M, varargin)
    %MAKEGEOMETRY Create schema-compliant geometry structure
    %
    % Syntax:
    %   geom = bct.schema.geometry.make(M)
    %   geom = bct.schema.geometry.make(M, 'precision', 'double', ...)
    %
    % Inputs:
    %   M - bct.Manifold object
    %
    % Optional Name-Value Arguments:
    %   precision          - 'double' (default) or 'single'
    %   circumcenterMethod - 'native' (default) or 'triangulation'
    %   boundaryPolicy     - 'error' (default), 'warn', or 'clip'
    %   dualCellType       - 'circumcentric' (default), 'barycentric', or 'mixed'
    %
    % Examples:
    %   M = bct.Manifold(V, F);
    %   geom = bct.schema.geometry.make(M);
    %   geom = bct.schema.geometry.make(M, 'precision', 'single');
    
    p = inputParser;
    p.addRequired('M', @(x) isa(x, 'bct.Manifold'));
    p.addParameter('precision', 'double', @(x) ischar(x) || isstring(x));
    p.addParameter('circumcenterMethod', 'native', @(x) ischar(x) || isstring(x));
    p.addParameter('boundaryPolicy', 'error', @(x) ischar(x) || isstring(x));
    p.addParameter('dualCellType', 'circumcentric', @(x) ischar(x) || isstring(x));
    p.parse(M, varargin{:});
    
    % Use the actual geometry computation function
    geom = bct.manifold.geometry(M, ...
        'precision', p.Results.precision, ...
        'circumcenterMethod', p.Results.circumcenterMethod, ...
        'boundaryPolicy', p.Results.boundaryPolicy, ...
        'dualCellType', p.Results.dualCellType);
    
    % Validate
    bct.schema.geometry.validate(geom);
end
